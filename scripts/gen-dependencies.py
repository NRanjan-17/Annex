#!/usr/bin/env python3
"""Regenerates docs/DEPENDENCIES.md from Cargo metadata and NuGet lock files.
Run: python3 scripts/gen-dependencies.py   (needs cargo)"""
import json, os, subprocess, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", os.path.join(ROOT, "core/Cargo.toml")]))
ws = set(meta["workspace_members"])
pkgs = {p["id"]: p for p in meta["packages"]}
direct = {}
for m in ws:
    for d in pkgs[m]["dependencies"]:
        if d.get("path") is None:
            direct.setdefault(d["name"], set()).add(pkgs[m]["name"])
rows = sorted((p["name"], p["version"], p.get("license") or "?") for i, p in pkgs.items() if i not in ws)

out = ["# Dependencies", "",
       "Generated by `scripts/gen-dependencies.py`; do not edit by hand. License policy is enforced",
       "by `cargo deny` (core/deny.toml): permissive licenses only, GPL video encoders banned.", "",
       "## Direct Rust dependencies", "", "| Crate | Version | License | Used by |", "|---|---|---|---|"]
latest = {}
for n, v, l in rows:
    latest[n] = (v, l)
for n in sorted(direct):
    v, l = latest.get(n, ("?", "?"))
    out.append(f"| {n} | {v} | {l} | {', '.join(sorted(direct[n]))} |")
out += ["", f"## All Rust crates in the build graph ({len(rows)})", "", "| Crate | Version | License |", "|---|---|---|"]
out += [f"| {n} | {v} | {l} |" for n, v, l in rows]

out += ["", "## .NET packages (Windows app)", "", "| Package | Version | Type | Project |", "|---|---|---|---|"]
for lock in sorted(glob.glob(os.path.join(ROOT, "apps/windows/**/packages.lock.json"), recursive=True)):
    proj = os.path.basename(os.path.dirname(lock))
    data = json.load(open(lock))
    for tfm, deps in data.get("dependencies", {}).items():
        if "/" in tfm:
            continue
        for name, info in sorted(deps.items()):
            if info.get("type") in ("Direct", "Transitive"):
                out.append(f"| {name} | {info.get('resolved', '')} | {info['type']} | {proj} |")
out += ["", "Licenses of the Microsoft packages (Windows App SDK, SDK build tools, test SDK) are MIT",
        "or the Microsoft Software License for redistributable runtime parts; xunit is Apache-2.0.", "",
        "## macOS app", "", "System frameworks only (ScreenCaptureKit, VideoToolbox, AVFoundation, SwiftUI); no Swift packages.", ""]
open(os.path.join(ROOT, "docs/DEPENDENCIES.md"), "w").write("\n".join(out))
print("wrote docs/DEPENDENCIES.md:", len(direct), "direct,", len(rows), "total crates")
