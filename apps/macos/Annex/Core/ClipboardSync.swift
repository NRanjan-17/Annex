import AppKit

/// Watches this Mac's clipboard and writes what the other computer copied. macOS has no change
/// notification, so it checks `changeCount` twice a second, which costs nothing.
@MainActor
final class ClipboardSync {
    static let text = "text/plain;charset=utf-8"
    static let png = "image/png"

    /// Something was copied on this Mac (not written by `apply`).
    var onCopy: ((_ mime: String, _ data: Data) -> Void)?

    private let board = NSPasteboard.general
    private var seen: Int
    private var timer: Timer?

    init() { seen = NSPasteboard.general.changeCount }

    func start() {
        guard timer == nil else { return }
        seen = board.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// What's on the clipboard now, if it's text or a picture and not marked private.
    func current() -> (mime: String, data: Data)? {
        let types = board.types ?? []
        // Password managers mark what they copy; it never leaves this Mac.
        let secret = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        if types.contains(where: { secret.contains($0.rawValue) }) { return nil }
        // Copying a file in Finder also puts its icon on the clipboard; send its name, not the icon.
        if !types.contains(.fileURL) {
            if let png = board.data(forType: .png) { return (Self.png, png) }
            if let tiff = board.data(forType: .tiff),
               let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
                return (Self.png, png)
            }
        }
        if let s = board.string(forType: .string), !s.isEmpty { return (Self.text, Data(s.utf8)) }
        return nil
    }

    /// Puts what the other computer copied on this Mac's clipboard.
    func apply(mime: String, data: Data) {
        board.clearContents()
        if mime.hasPrefix("text/plain") {
            board.setString(String(decoding: data, as: UTF8.self), forType: .string)
        } else if mime == Self.png {
            board.setData(data, forType: .png)
        } else {
            return
        }
        // Don't send it straight back.
        seen = board.changeCount
    }

    private func check() {
        let count = board.changeCount
        guard count != seen else { return }
        seen = count
        if let item = current() { onCopy?(item.mime, item.data) }
    }
}
